#!/usr/bin/env bash
# Migration coverage gate (docs/REFACTOR_PLAN.md §5, item 4).
#
#   scripts/MapCheck.sh [--strict] [--no-lean]
#
# 1. Validates docs/migration/map.tsv (header `old<TAB>new<TAB>kind`; names fully qualified,
#    e.g. `Feec.Constraints.prop_4_17` or `LinearPMap.IsSkewAdjoint`; `new` is `-` for
#    `deleted-helper`; kind ∈ rename, generalize, corollary, dedup, counterexample,
#    deleted-helper).
# 2. Generates scripts/MapCheck.lean with `#check @X` for every `new` of map.tsv and every
#    backticked name in a `- named:/- cited:` item of docs/THESIS_MAP.md, and runs it
#    (requires an up-to-date `lake build Feec`); every #check must elaborate.
# 3. Reports coverage: rows of docs/migration/old_theorems.tsv whose name appears as `old` in
#    map.tsv; `main` rows may not be `deleted-helper`.
# 4. Every thesis result cited under Feec/ as `[QuennevilleBelair2015], Prop 4.17` (the citation
#    convention; the location may start on the next line) must have a section in THESIS_MAP.md.
#
# Exit status: nonzero on a failing #check, a malformed row, a `main` row mapped to
# `deleted-helper`, or a thesis citation missing from THESIS_MAP.md. With --strict, also nonzero
# while some row of old_theorems.tsv is not covered by map.tsv (the end-of-migration gate).
set -euo pipefail
cd "$(dirname "$0")/.."
STRICT=0; LEAN=1
for a in "$@"; do
  case "$a" in
    --strict) STRICT=1 ;;
    --no-lean) LEAN=0 ;;
    *) echo "usage: $0 [--strict] [--no-lean]" >&2; exit 2 ;;
  esac
done
LOG="$(mktemp /tmp/feec_mapcheck.XXXXXX.log)"
python3 - gen <<'EOF'
import re
names = []
seen = set()
def add(n, src):
    if n not in seen:
        seen.add(n); names.append((n, src))
for k, line in enumerate(open('docs/migration/map.tsv', encoding='utf-8')):
    if k == 0:
        continue
    f = line.rstrip('\n').split('\t')
    if len(f) == 3 and f[1] not in ('', '-'):
        add(f[1], 'map.tsv')
for line in open('docs/THESIS_MAP.md', encoding='utf-8'):
    if re.match(r'- (named|cited):', line):
        for n in re.findall(r'`([^`]+)`', line):
            add(n, 'THESIS_MAP.md')
def esc(n):
    return '.'.join('«' + c + '»' for c in n.split('.'))
with open('scripts/MapCheck.lean', 'w', encoding='utf-8') as g:
    g.write('import Feec\n\n/-! Generated by `scripts/MapCheck.sh`; do not edit.\n'
            'Every `new` name of `docs/migration/map.tsv` and every name of `docs/THESIS_MAP.md`. -/\n\n')
    for n, src in names:
        g.write(f'#check @{esc(n)} -- {src}\n')
print(f'MapCheck.lean: {len(names)} #check lines')
EOF
CHECK_FAIL=0
if [[ $LEAN -eq 1 ]]; then
  lake env lean scripts/MapCheck.lean > "$LOG" 2>&1 || true
  grep -E '^scripts/MapCheck\.lean:[0-9]+:[0-9]+: error' "$LOG" | cut -d: -f2 | sort -un | while read -r ln; do
    echo "  #check failed: $(sed -n "${ln}p" scripts/MapCheck.lean)"
  done || true
  CHECK_FAIL=$(grep -cE '^scripts/MapCheck\.lean:[0-9]+:[0-9]+: error' "$LOG" || true)
  echo "#check failures: $CHECK_FAIL (log: $LOG)"
fi
python3 - "$STRICT" "$CHECK_FAIL" <<'EOF'
import re, sys, pathlib
strict, check_fail = int(sys.argv[1]), int(sys.argv[2])
KINDS = {'rename', 'generalize', 'corollary', 'dedup', 'counterexample', 'deleted-helper'}
errors = []
old = {}
for line in open('docs/migration/old_theorems.tsv', encoding='utf-8'):
    f = line.rstrip('\n').split('\t')
    old[f[0]] = (len(f) > 2 and f[2] == 'main')
rows = [l.rstrip('\n').split('\t') for l in open('docs/migration/map.tsv', encoding='utf-8')]
if rows[0] != ['old', 'new', 'kind']:
    errors.append(f'map.tsv: bad header {rows[0]}')
mapped = {}
for k, f in enumerate(rows[1:], start=2):
    if len(f) != 3:
        errors.append(f'map.tsv:{k}: expected 3 columns, got {len(f)}: {f}'); continue
    o, n, kind = f
    if kind not in KINDS:
        errors.append(f'map.tsv:{k}: unknown kind {kind!r}')
    if kind == 'deleted-helper' and n not in ('', '-'):
        errors.append(f'map.tsv:{k}: deleted-helper must have new = -')
    if kind != 'deleted-helper' and n in ('', '-'):
        errors.append(f'map.tsv:{k}: {kind} needs a new name')
    if o not in old:
        print(f'  note: map.tsv:{k}: old name {o} is not in old_theorems.tsv')
    mapped.setdefault(o, set()).add(kind)
for o, kinds in mapped.items():
    if old.get(o) and 'deleted-helper' in kinds:
        errors.append(f'main declaration {o} mapped to deleted-helper')
tot = len(old); cov = sum(1 for o in old if o in mapped)
mtot = sum(old.values()); mcov = sum(1 for o, m in old.items() if m and o in mapped)
print(f'coverage: {cov}/{tot} old declarations mapped ({tot - cov} missing); '
      f'main {mcov}/{mtot}; map.tsv rows {len(rows) - 1}')
# thesis citations `[QuennevilleBelair2015], <ids>`
RES = re.compile(r'\b(Theorem|Thm|Proposition|Prop|Corollary|Cor|Lemma|Remark|Definition|Def)s?\.?\s+(\d+\.\d+)')
KIND = {'theorem': 'Thm', 'thm': 'Thm', 'proposition': 'Prop', 'prop': 'Prop', 'corollary': 'Cor',
        'cor': 'Cor', 'lemma': 'Lemma', 'remark': 'Remark', 'definition': 'Def', 'def': 'Def'}
heads = set(re.findall(r'^### (.+)$', open('docs/THESIS_MAP.md', encoding='utf-8').read(), re.M))
CITE = re.compile(r'\[QuennevilleBelair2015\](?![\[(])(?:,\s*)?((?:[^\n;`\[]|\[(?![A-Z][A-Za-z\-]*\d{4}[a-z]?\]))*)')
ncite = 0
for p in sorted(pathlib.Path('Feec').rglob('*.lean')):
    src = p.read_text(encoding='utf-8')
    for c in CITE.finditer(src):
        for m in RES.finditer(c.group(1)):
            ncite += 1
            i = f'{KIND[m.group(1).lower()]} {m.group(2)}'
            if i not in heads:
                k = src.count('\n', 0, c.start()) + 1
                errors.append(f'{p}:{k}: thesis citation {i} has no section in THESIS_MAP.md')
print(f'thesis citations checked: {ncite}')
for e in errors:
    print('  ERROR ' + e)
bad = bool(errors) or check_fail > 0 or (strict and cov < tot)
print('MapCheck: ' + ('FAIL' if bad else 'OK') + (' (strict)' if strict else ''))
sys.exit(1 if bad else 0)
EOF
